-- ============================================
-- SiteSettingsテーブルの初期データ
--
-- 【行が無くても、アプリは動く】
-- SiteSettingsクラスは、DBが読めない場合も、行が無い場合も、
-- コードに埋め込んだ既定値で動き続ける（フェイルオープン）。
-- そのためこのINSERTは「動かすために必須」ではなく、
-- 「管理画面から変えられる状態にしておくため」に入れている
--
-- 【時間は、すべて秒で書く】
-- コード側がTimeSpan.FromSeconds()で戻す。1時間なら3600、10分なら600。
-- 管理画面に「単位」という余計な概念を持ち込まないため、秒に統一している
--
-- 【下限・上限は、ここには無い】
-- 丸めの範囲はコード側（SiteSettings.BuildSnapshot）が持つ。
-- DBが読めないときも丸めが効かなければならないため、範囲はコード側にしか置けない。
-- 各設定の範囲と、その根拠は SiteSettings.vb の公開プロパティのコメントにある
--
-- 【Scope・DisplayName・Category・SortOrderは、管理画面のための列。コードは読まない】
--   Scope       … この設定がいつ効くか（Server / Client / Both / Restart）
--   DisplayName … 管理画面に出す日本語の項目名
--   Category    … 管理画面でのまとまり（日本語。そのまま画面へ出せる）
--   SortOrder   … 表示順。10刻みで空けてあり、後から間に挿せる
--
-- 【何度実行しても、結果は変わらない】
-- 既にある行は書き換えない。運用中に変更した値を、
-- このスクリプトを流し直したせいで初期値へ戻してしまわないため
-- ============================================

