INSERT INTO SiteSettings (SettingKey, SettingValue, Scope, Category, SortOrder, DisplayName, Description)
SELECT s.SettingKey, s.SettingValue, s.Scope, s.Category, s.SortOrder, s.DisplayName, s.Description
FROM @Seed AS s
WHERE NOT EXISTS (
    SELECT 1 FROM SiteSettings AS t WHERE t.SettingKey = s.SettingKey
);


-- 既にある行は、管理画面のための列だけを最新に揃える
--
-- 【SettingValue は絶対に触らない】
-- あの列は運用者が管理画面から変える値で、このスクリプトが持っている値は
-- 「新しいサーバーで最初に入れる値」でしかない。上書きすると、
-- スクリプトを流し直しただけで運用中の設定が初期値へ戻る。
--
-- 【逆に、残りの列はこちらが持ち主である】
-- DisplayName・Description・Category・SortOrder・Scope は、管理画面に出すための表示で、
-- 運用者が編集する対象ではない（設計上、編集できるのは SettingValue だけ）。
-- そのため、ここで毎回上書きしてよい。
--
-- こうしておかないと、説明文を直しても本番へは永久に届かない
-- （「まだ無い行だけを入れる」ので、既にある行の説明文は古いまま残る）。
-- 実際、通知音の大きさを3段階から5段階へ増やしたとき、
-- 説明文だけが「low / normal / high」と書かれたまま取り残されるところだった
UPDATE t
SET t.Scope       = s.Scope,
    t.Category    = s.Category,
    t.SortOrder   = s.SortOrder,
    t.DisplayName = s.DisplayName,
    t.Description = s.Description
FROM SiteSettings AS t
INNER JOIN @Seed AS s ON s.SettingKey = t.SettingKey;
