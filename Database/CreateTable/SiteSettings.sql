-- ============================================
-- SiteSettingsテーブル
-- コードのあちこちに直接書かれていた設定値（文字数の上限、連投の間隔など）を、
-- 一か所へ集めて保管するためのテーブル
--
-- 【真実はDB側にあり、メモリはただのキャッシュ】
-- 読み出しはSiteSettingsクラス（ルート直下）が窓口になり、値をキャッシュする。
-- そのため、このテーブルへのアクセスは「アプリの起動後に1回」だけで、
-- 利用者の操作のたびに読みに来ることはない。
-- 値を変更したら、SiteSettings.Reload()を呼んでキャッシュを捨てること
-- ============================================

CREATE TABLE SiteSettings (

    -- 設定の名前
    -- SiteSettingsクラスの中で、Constとして同じ文字列を持っている。
    -- SQL Serverの既定の照合順序は大文字・小文字を区別しないため、
    -- 管理画面で "maxmessagelength" と打たれても同じ行に当たる
    SettingKey NVARCHAR(50) NOT NULL PRIMARY KEY,

    -- 設定の値
    --
    -- 【なぜ、型ごとに列を分けないのか】
    -- 読む側（SiteSettingsクラス）は、その設定が数値なのか文字列なのかを
    -- 最初から知っている。型の列を作ると「DBに書かれた型」と「コードが期待する型」が
    -- 食い違う余地が生まれ、しかもその食い違いはDBを見ても分からない。
    -- 文字列で持ち、読む側がGetInt / GetStringで解釈する形にしている
    --
    -- 【時間は、すべて秒で書く】
    -- 現状のコードはFromSeconds / FromMinutes / FromHoursが混ざっているが、
    -- DBには秒で統一して入れる（1時間なら3600）。
    -- ミリ秒への変換が要るのはJavaScriptへ渡すときだけで、
    -- それはJSONを組み立てる1か所でまとめて行う
    --
    -- 空文字と「行が無い」を区別する意味が無いため、NOT NULLにしている。
    -- 値を空にしたい設定は、今のところ存在しない
    SettingValue NVARCHAR(200) NOT NULL,

    -- この設定が、いつ効くか（管理画面に出す。コードは読まない）
    --
    --   Server  … Reload() ですぐ効く
    --   Client  … ブラウザへ渡る値。今ページを開いている人には効かず、
    --             再読み込みするまで古いまま
    --   Both    … サーバー側は即、ブラウザ側は再読み込み後
    --   Restart … アプリを再起動するまで効かない
    --
    -- 管理者にとっての実害は「変えたのに効かない」である。
    -- Descriptionの文章に埋めると一覧で見分けられないため、独立した列にしている
    --
    -- 【重要】この列でJSONの中身を決めてはいけない。
    -- WHERE Scope IN ('Client','Both') で引いてそのままJSONにすると、
    -- 丸めが効かず（門番を素通りする）、単位変換が効かず（ミリ秒へ直すものがある）、
    -- 型が全部文字列になる。JSONは丸めと型変換が済んだSnapshotから作ること
    Scope NVARCHAR(10) NOT NULL DEFAULT N'Server',

    -- 管理画面に出す、日本語の項目名（コードは読まない）
    --
    -- 無いと、管理画面のラベルが「MaxMessageLength」になる。
    --
    -- 【Descriptionとは役割が別】
    --   DisplayName … これは何か
    --   Description … 変えるときの注意
    --
    -- 【なぜコード側に「キー→日本語名」の対応表を持たないのか】
    -- 設定を1つ足すたびに、DBとコードの2か所を触ることになるため。
    -- 名前はDBが持ち、コードは知らない
    --
    -- 単位（秒・文字・件）は、当面この名前の中に「（秒）」の形で入れる
    DisplayName NVARCHAR(50) NOT NULL DEFAULT N'',

    -- 管理画面での、まとまり（コードは読まない）
    --
    -- 【日本語で持つ】
    -- DisplayNameが日本語なので、Categoryも日本語にすればそのまま画面へ出せる。
    -- 英語のキーにすると「キー→日本語」の対応表がまた要ることになり、
    -- 設定を足すたびにDBとコードの2か所を触る形へ逆戻りする
    Category NVARCHAR(30) NOT NULL DEFAULT N'その他',

    -- 表示順（コードは読まない）
    --
    -- 【1列で、カテゴリの並びと、カテゴリ内の並びを兼ねる】
    --   カテゴリの表示順 … そのカテゴリに属する行の、最小のSortOrder
    --   カテゴリ内の順   … SortOrderそのまま
    --
    -- 10刻みで空けてある。後から間に1つ挿したいとき、前後を振り直さずに済むため
    -- （ChatMessageTypeのEnumを10刻みで採番しているのと、同じ考え方）
    SortOrder INT NOT NULL DEFAULT 0,

    -- 管理画面に出す説明文
    --
    -- 【ここに、注意書きも書く】
    -- 例えばDefaultIconColor（アイコンの初期色）には、
    -- 「Content/theme.cssの--color-accentと同じ値にしておくこと」と書いておく。
    -- 設定を変える人が、変えた影響の及ぶ範囲をその場で読めるようにするため。
    -- NVARCHAR(500)にしてあるのは、注意書きが1行で収まらないことがあるため
    -- （NVARCHARは可変長のため、長くしても使っていない分の容量は消費しない）
    Description NVARCHAR(500) NULL,

    -- 最後に変更した日時（ミリ秒まで保持する）
    -- ChatMessages.CreatedAtと精度を揃えている
    UpdatedAt DATETIME2(3) NOT NULL DEFAULT SYSDATETIME()

);


-- ============================================
-- 索引（インデックス）について
-- ============================================
-- SettingKeyがPRIMARY KEYのため、既にクラスタ化索引が作られている。
-- 検索はこの1列でしか行わず、行数も数十行にしかならないため、
-- 追加の索引は作らない


-- ============================================
-- 管理画面から編集させるのは SettingValue だけ
-- ============================================
-- SettingKey・Scope・DisplayName・Category・SortOrder・Description・UpdatedAt は、
-- 表示のみで編集させない。
--
-- 「変えられたら困る」は、テーブルの設計ではなく画面の設計で解く。
-- とくに Scope を書き換えられると、サーバー内部の値をブラウザへ出す道ができる。
-- それを約束ではなく、画面の作りで防ぐ


-- ============================================
-- 下限・上限の列を、あえて作っていない理由
-- ============================================
-- 「この設定は1～900の範囲」といった丸めの範囲は、コード側（SiteSettingsクラス）が持つ。
--
-- 【本当の理由は「管理画面から変えられるから」ではない】
-- それは、上のとおり画面側で編集させなければ防げる。
-- 本当の理由は、**DBが読めないときも丸めが効かなければならない**からである。
-- SiteSettingsは、DBから1行も読めなくてもコードの既定値で動き続ける
-- （フェイルオープン）。そのとき既定値そのものも範囲へ丸めているが、
-- 範囲がDBにあったら、その範囲自体が読めない。
-- つまり範囲はコード側に無いと、原理的に成立しない。
--
-- 具体的に、次の3つは範囲を外すとエラーも出さずに壊れる。
--   ・LeaveGrace（退室猶予）を、見回りタイマーより短くする
--   ・MaxMessageLengthを、ChatMessages.MessageTextの列幅（1000）より大きくする
--   ・キープアライブの間隔を、Sessionのタイムアウト（20分）より長くする
--
-- 【丸めは2段構えであること】
-- 値ごとの下限・上限だけでは、上の1つ目のような**設定どうしの関係**は表せない。
-- 実際、範囲を入れただけの状態では「退室猶予4秒・見回り5秒」が素通りした
-- （2026年9月2日に実測）。SiteSettings側では、
--   1段目：値ごとの範囲（Clamp）
--   2段目：設定どうしの関係（AtLeastLongerThan）
-- の2段で丸めている
