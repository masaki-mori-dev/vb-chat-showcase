-- ============================================
-- UsedFormTokensテーブル（2026年9月30日、二重送信を防ぐ「使い捨ての目印」）
-- 送信に使われた目印＝1行
--
-- 【何のための表か】
-- 送信が済んだあと、戻るボタンで入力の画面に戻って、もう一度押すと、同じものがもう1件入る。
-- それを止めるために、画面を描くたびに目印を1つフォームに入れ、サーバーは同じ目印を1回しか受け付けない。
-- 「この目印は、もう使った」を覚えておくのが、この表である（仕組みは Core/FormOnce.vb）。
--
-- 【なぜメモリではなく DB なのか】
-- 共用サーバーは、人が居ないとアプリが休んで起き直す。メモリは起き直すと消えるので、
-- 「送信 → しばらく放置 → 戻って押し直す」が素通りする。DB なら、起き直しても覚えている。
-- 主キーなので、ほとんど同時に2回届いたとき（ボタンの連打）も、片方だけが通る。
--
-- 【入っているのは、でたらめな32文字と時刻だけ】誰が・何を送ったかは入らない（個人情報は無い）。
--
-- 【古い行は、1日1回の仕事 LogCleanup が消す】（30日より前。Core/FormOnce.vb の KeepDays）
--
-- 【この表が無いまま新しいコードを発行しても、サイトは動く】
-- 目印を書けなかったときは、止めずに通す作りである（二重送信を防げないだけ。エラー報告メールが届く）。
-- それでも、順番は DB → コード（表を先に作ってから、それを使うコードを発行する）。
--
-- 【流す順番】どの表にも依存していないので、いつでもよい（外部キーが1つも無い）
--
-- 【何度流しても安全な形にしてある】既にテーブルがあれば、何もしない（中身も消さない）
-- ============================================

IF OBJECT_ID(N'UsedFormTokens', N'U') IS NULL
BEGIN

    CREATE TABLE UsedFormTokens (

        -- 目印（小文字の16進で32文字。Core/FormOnce.vb の NewToken が作る）
        --
        -- 【CHAR(32)】長さが決まっていて、英数字だけなので、NVARCHAR にする意味が無い。
        -- 形の合わないものは、コードが DB へ渡す前に捨てている
        Token CHAR(32) NOT NULL,

        -- 使った時刻
        --
        -- 【DBの時計で入れる】既定値のまま書くこと。古い行を消すとき（LogCleanup）は、この列で決める
        UsedAt DATETIME2(3) NOT NULL CONSTRAINT DF_UsedFormTokens_UsedAt DEFAULT SYSDATETIME(),

        -- 【主キーが、二重送信を止める本体である】同じ目印の2度目の INSERT は、ここで失敗する
        CONSTRAINT PK_UsedFormTokens PRIMARY KEY (Token)

    );

    -- 古い行を消すときの索引（1日1回。消す量はごく少ないが、表全体を舐めないように）
    --
    -- 【フィルター付きの索引にしていない】ので、sqlcmd から手で流すときに SET QUOTED_IDENTIFIER は要らない
    CREATE INDEX IX_UsedFormTokens_UsedAt ON UsedFormTokens (UsedAt);

END
GO
