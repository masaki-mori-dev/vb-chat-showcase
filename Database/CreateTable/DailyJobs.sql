-- ============================================
-- DailyJobsテーブル（2026年9月15日、13-2b）
-- 「1日1回の仕事」ごとに、どの日付の分まで済んだかを覚える表。
-- 1行＝仕事1つ（今は集計メール DailyReport だけ。15番の古いログの削除も、ここに乗る）
--
-- 【なぜ「前回から24時間」ではなく「どの日付まで済んだか」なのか】
-- 共用サーバーは、アクセスが無いとアプリを寝かせる。起きる時刻はこちらで選べない。
-- 「前回から24時間」だと、寝ていた日のぶんが丸ごと抜けたり、日付の境目とずれたりする。
-- 「9月14日の分まで済んだ」と覚えておけば、何日寝ていても、起きたときに抜けた日をまとめて片付けられる
--
-- 【なぜDBなのか（メモリではないのか）】
-- IIS はアプリを入れ替えるとき、新しいアプリと古いアプリを一瞬並べて動かす。
-- メモリ上のロックは、それぞれのアプリの中でしか効かないので、同じ仕事が2回走りうる。
-- 取りかかるときは UPDATE 1本で「作業中」の印（LeaseUntil・LeaseToken）を取り、
-- 取れた1本だけが働く（DailyJobs.vb）
--
-- 【行は、コードが無ければ作る】
-- 仕事の名前はコード（DailyJobs.vb の仕事の一覧）が持ち、行が無ければ最初に見に行ったときに作る。
-- 行を手で入れる形にしないのは、入れ忘れたときに**黙って一度も動かない**ため。
-- このスクリプトは表を作るだけで、行は入れない
--
-- 【日付は DB の時計で決める】
-- ChatMessages.CreatedAt が DB の時計（SYSDATETIME()）で入っているため。
-- 「昨日」も「作業中の期限」も、DB の SYSDATETIME() から出す
--
-- 【何度流しても安全な形にしてある】
-- 既にテーブルがあれば、何もしない（中身も消さない）
-- ============================================

IF OBJECT_ID(N'DailyJobs', N'U') IS NULL
BEGIN

    CREATE TABLE DailyJobs (

        -- 仕事の名前（コードの DailyJobs.vb が持つ名前と同じ）。例: 'DailyReport'
        JobName NVARCHAR(50) NOT NULL PRIMARY KEY,

        -- この日付の分まで済んだ（NULL＝まだ一度も済ませていない＝最初は「昨日」の分から）
        --
        -- 【送り終わってから書く】済ませる前に書くと、途中で失敗した日が「済んだ」ことになって二度と来ない。
        -- 【送らない設定のときも進める】進めないと、オンに戻した日に止めていた間の日がどっと来る
        DoneThrough DATE NULL,

        -- 作業中の期限（NULL＝誰も作業していない）
        --
        -- 取りかかった1本がここに「今＋10分」を書く。期限までは、ほかのアプリはこの仕事を取れない。
        -- 済んだら NULL に戻す。**失敗したときは戻さない**＝期限が切れた10分後に、どれかのアプリがやり直す
        -- （途中でアプリが止まったときも同じ。印を外す人が居なくても、期限が切れれば取れる）
        LeaseUntil DATETIME2(0) NULL,

        -- 作業中の印を取ったのが誰か（取った1本が作る使い捨ての値）
        --
        -- 済んだ日付を書くときに、この値が自分のものと同じかを確かめる。
        -- 期限が切れて別のアプリに取られたあとで、古いほうが済んだ日付を書き換えないため
        LeaseToken UNIQUEIDENTIFIER NULL,

        -- 最後に済ませた・試した時刻と、その結果（記録。コードの判断には使わない）
        -- 例: 「送った（9月14日）」「送らない設定なので送らなかった」「送れなかった：…」
        -- 本番で動いているかを SSMS で見るため（SELECT * FROM DailyJobs）
        LastRunAt DATETIME2(0) NULL,
        LastResult NVARCHAR(400) NULL

    );

END
