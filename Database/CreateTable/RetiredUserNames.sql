-- ============================================
-- RetiredUserNamesテーブル（2026年9月29日、一般ユーザーの登録の「退会」）
-- 退会した人のユーザー名の控え。1行＝もう誰にも使わせない名前1つ
--
-- 【何のための表か】退会は**物理削除**（Accounts の行ごと消す）なので、
-- そのままだと**別の人が同じユーザー名で登録できる**。
-- ユーザー名はブログのアドレス（/articles/{ユーザー名}）と、公開のプロフィールの
-- アドレス（/profile/{ユーザー名}）にそのまま出る。**前の人のアドレスを引き継いだ人は、
-- 検索やブックマークから来た人には「同じ人」に見える**――なりすましになる。
-- そこで、**使われた名前だけを、ここに残す。**
--
-- 【メールアドレスは残さない】
-- 残すと「同じ人がもう一度登録する」ができなくなる。
-- 名前だけなら、別の名前を選んでもらえばよい。
--
-- 【この表に個人を特定できるものは無い】ユーザー名と、退会した時刻だけ。
-- 表示名・メールアドレス・記事・プロフィールは、退会の時点で全部消えている。
--
-- 【アカウントを指す番号（AccountId）も残さない】残すと、消したはずの行との
-- つながりが残ってしまう（退会したら全部消す、という形にならない）。
--
-- 【流す順番】どこでもよい（外部キーを1本も持たない）。
-- Accounts.sql と同じ回に流す。
--
-- 【何度流しても安全な形にしてある】既にテーブルがあれば、何もしない（中身も消さない）
-- ============================================

IF OBJECT_ID(N'RetiredUserNames', N'U') IS NULL
BEGIN

    CREATE TABLE RetiredUserNames (

        -- 使われた名前（Accounts.UserName と同じ列幅にしてある）
        --
        -- 【照合順序は既定のまま】大文字・小文字を区別しないので、
        -- 'Taro' で退会した人の名前は 'taro' でも引っかかる（それが狙いどおり）
        UserName NVARCHAR(30) NOT NULL,

        RetiredAt DATETIME2(3) NOT NULL
            CONSTRAINT DF_RetiredUserNames_RetiredAt DEFAULT SYSDATETIME(),

        CONSTRAINT PK_RetiredUserNames PRIMARY KEY (UserName)

    );

END
