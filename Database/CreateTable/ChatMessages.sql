-- ============================================
-- ChatMessagesテーブル
-- チャットの発言ログ・入退室ログを記録するテーブル
-- 発言と入退室イベントは、別テーブルに分けず1つにまとめ、
-- MessageType列で区別する（時系列で1本に並べて表示するため）
-- ============================================

CREATE TABLE ChatMessages (

    -- ログを一意に識別するID（自動採番）
    -- ログは行数がどんどん伸びていくため、INTではなくBIGINTにしている
    MessageId BIGINT IDENTITY(1,1) PRIMARY KEY,

    -- どの部屋のログか（ChatRooms.RoomIdに対応する）
    -- ただし外部キー制約は付けない（理由はファイル末尾のコメント参照）
    -- 0 = 部屋ではない（50番台の「サイトへの出入り」の行。ChatRooms の RoomId は1から振られる）
    RoomId INT NOT NULL,

    -- ログの種別
    -- 10 = 発言
    -- 11 = こっそりの発言（部屋の全員ではなく、1人だけに宛てた発言）
    --      宛先は RecipientBrowserId 列に入る。
    --      10の隣にしているのは、どちらも「人が打った文章」で性質が同じだから。
    --      10刻みの採番は、まさにこう間へ差し込むためにしてある
    -- 20 = 入室
    -- 30 = 退室（退室ボタンを押した）
    -- 31 = 切断退室（ブラウザ・タブを閉じた、通信が切れた）
    -- 32 = 無言タイムアウト退室（既定1時間、発言が無いまま経過）
    -- 33 = 強制退室：システム（同一ブラウザの別接続に置き換えられた）
    -- 34 = 強制退室：部屋のオーナーによるキック（将来実装）
    -- 35 = 強制退室：サイト管理者によるキック（将来実装）
    -- 36 = 応答なし（現在は未使用。番号の予約）
    -- 37 = ログアウト（部屋の窓を開いたまま、ラウンジでログアウトした。2026年9月10日に追加）
    -- 退室系を30番台にまとめているのは、在室期間を復元する際に
    -- 「30番台ならどれでも在室終了」と範囲で判定できるようにするため
    -- 40 = 入室拒否：満員だった（部屋にいた記録ではなく、入ろうとして断られた記録）
    -- 40番台は「入室できなかった記録」で、在室期間の復元には使わない。
    -- LocalIdは常にNULL（番号が発行される前に断っているため）
    -- 41以降は、他の入室拒否の理由（終了した部屋・パスワード違いなど）のために空けてある
    -- 50番台は「サイトへの出入り」（部屋の外の出来事。RoomId = 0。2026年9月15日、13-2a）
    -- 50 = ログイン（トップで名前を決めて、ラウンジに来た）
    -- 51 = ログアウト（ラウンジのボタン。部屋に席があれば、その部屋には37も書く）
    -- 52 = ラウンジに来た（1つのブラウザにつき1日1回。部屋に入らずに帰った人も数えるため）
    -- どれも1つのブラウザにつき1日1回までで、覚えておくのはアプリのメモリ。
    -- アプリが起き直すと同じ日にもう1回書くことがあるので、数えるときは SenderBrowserId の DISTINCT で数える
    -- 60番台以降は、入退室以外の別カテゴリ（部屋作成など）のために空けてある
    MessageType TINYINT NOT NULL,

    -- アカウントの番号（Accounts.AccountId）
    -- 【入るのは、アカウントID を表示してチャットに参加している人の行だけ】（2026年9月30日、チャットとアカウントの紐づけ）
    -- 名乗らずに参加している人・アカウントを持たない人の行は、今までどおり NULL
    -- 値を入れるのは ChatLog.Write（Participant.AccountId。サーバーがログインの印から決めた値）
    -- 【ユーザー名は焼き込まない】読むときに Accounts を引く。退会・停止で、過去ログからアカウントID が消える
    -- 【退会したら NULL に戻す】（AccountStore.DeleteAccountCompletely。行そのものは残る）
    -- 外部キーは付けない（ログの表は書き込みが多く、消す順番にも縛られたくないため。RoomId と同じ）
    UserId INT NULL,

    -- 部屋の中でのみ通用する、一時的な番号
    LocalId INT NULL,

    -- 発言した人（＝この行を起こした人）のChatBrowserId Cookie
    -- 将来、Cookie利用者が後からアカウントを作った際に、
    -- 過去の発言と紐づけられる可能性を残すために記録する
    --
    -- 【なぜ「Sender」と付いているのか】
    -- 下の RecipientBrowserId（宛先）と対になるため。
    -- 元は単に BrowserId という名前だったが、宛先の列が隣に並ぶと
    -- どちらの向きの印なのかが読めなくなるため、役割を名前に入れた
    -- （ChatRooms.OwnerBrowserId と同じ付け方）
    SenderBrowserId UNIQUEIDENTIFIER NULL,

    -- こっそりの発言（種別11）の、宛先のChatBrowserId Cookie
    -- こっそり以外の行では、常にNULLが入る
    --
    -- 【なぜ宛先の列が要るのか】
    -- 普通の発言も宛先は記録している。それが RoomId で、
    -- 「この部屋に居る全員宛て」という意味である。
    -- こっそりは宛先が部屋ではなく1人なので、RoomId ではその1人を表せない。
    -- 宛先を書かないと「自分宛ての行」を自分のものだと判定できない
    -- （自分が送った行は SenderBrowserId で絞れるが、
    --   相手から来た行を拾う手がかりがゼロになる）
    --
    -- 【なぜ、宛先のニックネームを焼き込まないのか】
    -- 往復すれば、相手の名前は相手自身の行にある。
    -- 本体のログとこっそりのログで、別々に相手の名前を持つのはおかしい
    --
    -- 【なぜ LocalId で持たないのか】
    -- LocalId の発番カウンターはメモリ上にあり、アプリが再起動すると1に戻る。
    -- 同じ部屋の「LocalId = 3」が、別の日には別人になる
    RecipientBrowserId UNIQUEIDENTIFIER NULL,

    -- 発言した時点のニックネーム（スナップショット）
    -- Cookieの値はいつでも変更できるため、後から参照する形にすると
    -- 過去ログの表示まで変わってしまう。そのため、その時点の値をログに焼き込む
    Nickname NVARCHAR(50) NOT NULL,

    -- 発言した時点のアイコン種別（スナップショット。理由はNicknameと同じ）
    IconType NVARCHAR(30) NULL,

    -- 発言した時点のアイコン色（スナップショット。理由はNicknameと同じ）
    IconColor NVARCHAR(10) NULL,

    -- 発言した時点のトリップ（16進10桁。スナップショット。理由はNicknameと同じ）
    -- 合言葉を入れていない人の行と、トリップ機能が止まっているときは NULL。
    -- 名前の列にくっつけないのは、画面で色・書体・置き場所を分けて出すため。
    -- 幅は Chat/TripCode.vb の Length と同じ数にしておくこと
    Trip NVARCHAR(10) NULL,

    -- 発言の本文
    -- 入室・退室などのイベント行では、本文が無いためNULLが入る
    -- 長文の投げ込みによる表示崩れを防ぐため、NVARCHAR(MAX)にはしない
    MessageText NVARCHAR(1000) NULL,

    -- その行が画像の発言なら、その画像のGUID（画像以外の行では常にNULL）
    --
    -- 画像の発言は、本文（MessageText）に
    --     [img:2026/09/10/<GUIDの32桁>.jpg:1280x960]
    -- という印だけが入る。この列には、そのうちの **GUIDの部分だけ** を入れる。
    --
    -- 【なぜ、本文に入っているものを、わざわざ列にも持つのか】
    -- こっそりの画像（種別11）は、静的ファイルとして配らずに .aspx を通し、
    -- **その画像を見てよい人かどうかを毎回確かめる**。確かめるには、
    -- その画像がどの発言のものかを引く必要がある。
    -- 本文から引くと LIKE になって索引が使えず、画像を1枚開くたびに
    -- ログを舐めることになる。列にしておけば、下の索引で一発で引ける。
    --
    -- 【RecipientBrowserId を足したときと、同じ判断である】
    -- 本文は**画面へ出すための形**、列は**引くための形**であり、役割が違う
    ImageName UNIQUEIDENTIFIER NULL,

    -- 発言元のIPアドレス
    -- IPv6の最大長（45文字）を考慮した長さにしている
    IpAddress NVARCHAR(45) NULL,

    -- 発言元のポート番号（接続元の、送り出し側の番号。0～65535）
    -- IpAddress と同じ行に、同じタイミングで入れる。取れなかったときは NULL。
    -- 携帯の回線などは1つの IP アドレスを大勢で分け合うので、IP アドレス＋ポート番号＋時刻がそろって、はじめて回線の会社が契約者を引ける
    RemotePort INT NULL,

    -- 記録した日時（ミリ秒まで保持する）
    -- ChatRooms.CreatedAtはDATETIMEだが、ログは時系列で扱うため、
    -- こちらは精度の高いDATETIME2を採用している
    CreatedAt DATETIME2(3) NOT NULL DEFAULT SYSDATETIME()

);

-- ============================================
-- 外部キー制約について
-- ============================================
-- RoomIdにChatRoomsへの外部キー制約は、あえて付けていない。
-- 理由は2つ。
--   1. ログテーブルは書き込みが非常に多く、制約のチェックが積み重なると負荷になるため
--   2. 1年を経過した古いログを定期的に削除する運用を予定しており、
--      制約によって削除の順序に縛られたくないため


-- ============================================
-- 索引（インデックス）
-- ============================================

-- 入室時に「その部屋の最新N件」を取得するための、主役の索引
-- 並び順にCreatedAtではなくMessageIdを使うのは、同じ時刻の発言が複数あった場合でも
-- 順序が一意に定まるようにするため
CREATE INDEX IX_ChatMessages_RoomId_MessageId
    ON ChatMessages (RoomId, MessageId DESC);

-- 1年を経過した古いログを削除する際に使う索引
CREATE INDEX IX_ChatMessages_CreatedAt
    ON ChatMessages (CreatedAt);

-- アカウントの人が、自分が参加したチャットの記録（/account/chatlogs）を読むための索引
-- 【形】
--   鍵     … (UserId, MessageId) ＝自分の行を、新しい順に並べる
--   添える列 … 入室・退室の行を探すときに見る列。索引だけで答えが出る（表の本体を読まない）
-- フィルター付きなので、アカウントID を表示していない人の行（ほとんどの行）は載らず、
-- その INSERT では更新も走らない
CREATE INDEX IX_ChatMessages_UserId
    ON ChatMessages (UserId, MessageId)
    INCLUDE (MessageType, RoomId, SenderBrowserId, CreatedAt)
    WHERE UserId IS NOT NULL;


-- こっそりの画像を1枚開くたびに、その画像の行を引くための索引
--
-- 【フィルター付きにしてあること】
-- 画像の行だけを載せる。文章・入退室の行は載らないので、索引そのものが
-- 小さいままで、それらのINSERTでは更新も走らない
-- （IX_ChatMessages_UserId と同じ考え方）
CREATE INDEX IX_ChatMessages_ImageName
    ON ChatMessages (ImageName)
    WHERE ImageName IS NOT NULL;
