-- ============================================
-- StampSetsテーブル
-- スタンプの「セット」（カエル・ヒヨコ…）の目次。
-- 発言に入れるものを選ぶパネルの、スタンプのタブ1つが、この表の1行に当たる
--
-- 【Stamps.sql より先に流すこと】
-- Stamps.SetCode が、この表の SetCode を外部キーで参照している。
-- 先に Stamps を作ろうとすると、参照先が無くて失敗する
--
-- 【何度流しても安全な形にしてある】
-- 既にテーブルがあれば、何もしない（中身も消さない）
--
-- 【中身（行）は、Database/InsertData/StampSets.sql が入れる】
-- あちらは素材から機械で書き出すファイルで、手では書き換えない。
-- 絵と目次を同じスクリプトが同時に書くので、両者がズレようがない
--
-- 【真実はDB側にあり、メモリはただのキャッシュ】
-- 読み出しは StampCatalog クラス（Chat/StampCatalog.vb）が窓口になり、
-- 読んだ結果を抱えておく。利用者がスタンプを何回押しても、この表は読みに来ない。
-- 行を変えたら StampCatalog.Reload() を呼ぶか、アプリを再起動すること
-- ============================================

IF OBJECT_ID(N'StampSets', N'U') IS NULL
BEGIN

    CREATE TABLE StampSets (

        -- セットの名前（英小文字・数字・ハイフン）。例: 'frog'
        --
        -- 【Content/Stamps/ の下のフォルダ名と同じ】
        -- 絵のファイルは Content/Stamps/<SetCode>/<FileName> に置く。
        -- URLの一部になるため、英小文字・数字・ハイフンだけにする
        -- （StampCatalog が読むときに確かめ、外れた行は使わない）
        --
        -- 【一度決めたら変えないこと】
        -- フォルダの名前であり、Stamps.SetCode から参照されている
        SetCode NVARCHAR(20) NOT NULL PRIMARY KEY,

        -- タブに出す名前。例: 'カエル'
        DisplayName NVARCHAR(50) NOT NULL,

        -- セットの並び順（タブの左から）
        -- 10刻みで空けてある。後から間に1つ挿したいとき、前後を振り直さずに済むため
        SortOrder INT NOT NULL,

        -- 1 = パネルに出す、0 = これからは出さない
        --
        -- 【0にしても、過去ログの絵は消えない】
        -- 意味は「これから選べなくする」だけである。
        -- 発言には [stamp:frog-01] の形で焼き込まれて残るので、
        -- 0にしたセットのスタンプも、過去ログではそのまま絵として出す。
        -- 行を消すと、その絵を引けなくなるので、消さずに0にすること
        IsActive BIT NOT NULL DEFAULT 1

    );

END
GO


